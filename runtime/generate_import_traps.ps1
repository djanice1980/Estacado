    '#include "runtime_harness.h"',
    '#include "ppc_recomp_shared.h"',
    ''
)
foreach ($symbol in $symbols) {
    # Imports are declared by PPC_EXTERN_FUNC with C++ linkage in the generated
    # shared header; retain that linkage so these traps satisfy the call sites.
    $lines += "PPC_FUNC($symbol) { RuntimeTrap(`"$symbol`", ctx, base); }"
}
Set-Content -LiteralPath $Output -Value $lines
Write-Output "Generated explicit traps for $($symbols.Count) imported entry points."
